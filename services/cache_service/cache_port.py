from typing import Any, Protocol

from domain.schema import CacheMessage


class CachePort(Protocol):
    """Defines how the application interacts with caching services"""

    async def _initialise(self) -> CachePort: ...
    async def is_message_processed(self, message_id: str) -> bool: ...
    async def get_chat_history(self, user_id: str, *args, **kwargs) -> list[Any]: ...
    async def add_to_chat_history(
        self, user_id: str, cache_message: CacheMessage, *args, **kwargs
    ) -> None: ...
    async def delete_user_chat_history(self, user_id: str, *args, **kwargs) -> bool: ...
    async def delete_user_cache_by_time(
        self, user_id: str, *args, **kwargs
    ) -> None: ...
    async def save_user_session(self, *args, **kwargs) -> None: ...
